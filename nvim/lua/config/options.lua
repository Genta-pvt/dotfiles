-- ============================================================
-- エディタオプション設定
-- ============================================================

-- -------------------------------------------------------
-- クリップボード
-- -------------------------------------------------------

-- システムクリップボードと連携（unnamed: "*レジスタ, unnamedplus: "+レジスタ）
vim.opt.clipboard:append('unnamedplus,unnamed')

-- -------------------------------------------------------
-- インデント / タブ
-- -------------------------------------------------------

vim.opt.tabstop    = 2      -- タブ幅（表示上）
vim.opt.shiftwidth = 2      -- 自動インデント幅
vim.opt.expandtab  = true   -- タブをスペースに展開
vim.opt.shiftround = true   -- インデントをshiftwidthの倍数に丸める

-- -------------------------------------------------------
-- 編集・操作
-- -------------------------------------------------------

-- mouse: マウス操作を有効にするモード（a=全モード）。
-- クリックでカーソル移動、ドラッグで範囲選択、ホイールでスクロール、
-- 分割境界のドラッグでリサイズが可能になる。
-- 注意: mouse 有効時はドラッグ選択が Vim 側に取られるため、
-- 端末ネイティブのコピーは Shift+ドラッグで行う
vim.opt.mouse = 'a'

-- virtualedit: カーソルを実際の文字が無い領域へ置けるようにする条件（block=矩形選択中のみ）。
-- 長さの異なる行でも <C-v> の矩形選択で行末を越えて選択・整列でき、縦揃え編集が楽になる
vim.opt.virtualedit = 'block'

-- -------------------------------------------------------
-- ファイル形式・エンコード
-- -------------------------------------------------------

vim.opt.fileencodings = "ucs-bom,utf-8,iso-2022-jp-3,euc-jp,cp932"
vim.opt.fileformats   = "unix,dos,mac"

-- -------------------------------------------------------
-- ウィンドウ分割
-- -------------------------------------------------------

vim.opt.splitright = true   -- 縦分割を右側に開く
vim.opt.splitbelow = true   -- 横分割を下側に開く

-- -------------------------------------------------------
-- 表示
-- -------------------------------------------------------

vim.opt.scrolloff    = 3     -- カーソル上下に常に3行余白を確保
vim.opt.number       = true  -- 行番号を表示
vim.opt.cursorline   = true  -- カーソル行をハイライト
vim.opt.termguicolors = true -- 24ビットカラーを有効化

-- カラースキームを設定（mini.nvim が提供する minischeme を使用）
vim.cmd.colorscheme('minischeme')

-- -------------------------------------------------------
-- ステータスライン（未保存バッファを色で強調）
-- -------------------------------------------------------

-- laststatus=2: 各ウィンドウに個別のステータスラインを表示する。
-- グローバルステータスライン（=3）だと 1 本に統合され、ウィンドウごとの
-- 未保存表示ができなくなるため、ここで明示的に 2 を指定する。
vim.opt.laststatus = 2

-- 未保存（modified）のときだけ、そのウィンドウのステータスラインを警告色へ切り替える式。
-- statusline の %{%...%} は「描画対象のウィンドウ／バッファをカレントにして」評価されるため、
-- vim.bo.modified はウィンドウごとの未保存状態を返す。これにより分割中でも各ウィンドウが
-- 自分の未保存状態を個別に色で表現できる（StatusLine を直接塗ると全ウィンドウ一律になってしまう）。
-- 戻り値の %#StatusLineModified# は行頭で適用するため、未保存時はバー全体が警告色になる。
-- StatusLineModified のハイライト定義は autocmds.lua 側で行う。
function _G.statusline_modified_hl()
  return vim.bo.modified and '%#StatusLineModified#' or ''
end

-- %{%...%}: 未保存ならバー全体を警告色に切替（未保存でない場合は通常の StatusLine/StatusLineNC）
-- %f ファイル名 / %h%w%m%r 各種フラグ / %= 右寄せ / %l:%c 行:列 / %P 表示位置
vim.opt.statusline = '%{%v:lua.statusline_modified_hl()%} %f %h%w%m%r%= %l:%c  %P '

-- -------------------------------------------------------
-- 検索・置換
-- -------------------------------------------------------

vim.opt.ignorecase = true      -- 大文字小文字を区別しない
vim.opt.smartcase  = true      -- 大文字が含まれる場合は区別する
vim.opt.inccommand = "split"   -- :%s の置換プレビューをsplitウィンドウで表示

-- -------------------------------------------------------
-- セッション・履歴
-- -------------------------------------------------------

-- shada: セッション間で保持する情報を設定
-- ! グローバル変数, '100 最近100ファイルのマーク, <50 レジスタ最大50行,
-- s10 最大10KBのアイテム, h hlsearch無効化, % バッファリスト保存
-- % を除外：起動時のバッファリスト復元を無効化（mini.sessions の autoread と競合するため）
vim.opt.shada = "!,'100,<50,s10,h"

-- undofile: undo 履歴をファイルに保存し、Neovim を再起動した後でも undo/redo を可能にする。
-- 保存先は stdpath('state')/undo（作業ディレクトリは汚さない）。
-- 注意: 編集履歴がディスクに残るため、秘匿情報を一時編集する際は留意する
vim.opt.undofile = true


vim.opt.shell = "powershell"
vim.opt.shellcmdflag = "-NoLogo -NoProfile -ExecutionPolicy RemoteSigned -Command"
vim.opt.shellquote = ""
vim.opt.shellxquote = ""
vim.opt.shellpipe = "| Out-File -Encoding UTF8 %s"
vim.opt.shellredir = "| Out-File -Encoding UTF8 %s"
